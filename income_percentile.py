def bin_average_man(top_pct):
    """특정 구간의 1인당 평균 총급여(만원)."""
    for p, n, total in NTS_BINS:
        if p == top_pct:
            return total * 10000 / n
    raise KeyError(top_pct)


def _boundaries():
    """(상위 %, 연봉 경계 만원) - 연봉 내림차순. 구간 i와 i+1 사이 경계 = 두 구간 평균의 기하평균."""
    avgs = [(p, total * 10000 / n) for p, n, total in NTS_BINS]
    return [(p, round(math.sqrt(a * avgs[i + 1][1])))
            for i, (p, a) in enumerate(avgs[:-1])]


# 기존 계산기(generate.py)의 JS·Python 보간 코드가 그대로 쓰는 형식: (상위 퍼센트, 연봉 만원), 퍼센트 오름차순
PERCENTILE_TABLE = _boundaries()

SOURCE_NOTE = f"국세청 {DATA_YEAR}년 귀속 근로소득 백분위(천분위) 원자료, 근로자 {TOTAL_WORKERS:,}명 기준 추정"


def estimate_top_percent(annual_man_won: float) -> float:
    """연봉(만원)을 받아 '상위 몇 %'를 반환. 표 범위 밖이면 양 끝값으로 고정."""
    table = PERCENTILE_TABLE
    if annual_man_won >= table[0][1]:
        return table[0][0]
    if annual_man_won <= table[-1][1]:
        return table[-1][0]

    for i in range(len(table) - 1):
        p_hi, v_hi = table[i]
        p_lo, v_lo = table[i + 1]
        if v_lo <= annual_man_won <= v_hi:
            ratio = (annual_man_won - v_lo) / (v_hi - v_lo)
            return round(p_lo - ratio * (p_lo - p_hi), 1)
    return table[-1][0]


