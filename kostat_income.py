# 업종 티어: 평균 월 소득 기준 컷. 재미용 구분이며 페이지에 기준을 그대로 공개한다.
INDUSTRY_TIER_CUTS = [("S", 650), ("A", 480), ("B", 400), ("C", 300), ("D", 0)]


def industry_tier(mean):
    for tier, cut in INDUSTRY_TIER_CUTS:
        if mean >= cut:
            return tier
    return "D"


def top_percent_in_group(monthly_man, key):
    """월 소득이 해당 집단에서 상위 몇 %인지. 구간 안에서는 고르게 분포한다고 보고 선형 보간.
    1,000만원 이상 구간은 상한이 없어 '상위 X% 이내'까지만 말할 수 있다 -> (값, 상한구간 여부)"""
    dist = DIST[key]
    if monthly_man >= BANDS[-1]:
        return dist[-1], True
    below = 0.0
    for i, share in enumerate(dist[:-1]):
        lo, hi = BANDS[i], BANDS[i + 1]
        if monthly_man < hi:
            below += share * (monthly_man - lo) / (hi - lo)
            break
        below += share
    return round(100 - below, 1), False


assert all(abs(sum(v) - 100) < 0.25 for v in DIST.values())
